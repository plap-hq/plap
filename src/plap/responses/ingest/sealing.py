"""
Exact wire formats for the sealed replay data in this module.

Key derivation
- All three sealers start from a 32-byte root key in `SealingKeyring`.
- For purpose `p`, the working key is:

    HKDF-SHA256(
        root_key,
        salt=None,
        info=b"plap:" + p,
        length=32,
    )

- Purpose strings used here:
  - `responses.ingest.call_id`
  - `responses.ingest.reasoning`
  - `responses.ingest.compaction`

Reasoning and compaction payloads
- Plaintext is deterministic `msgspec` JSON.
- Reasoning envelope:

    {
        "version": 6,
        "type": "reasoning",
        "id": <string>,
        "previous_reasoning_id": <string|null>,
        "previous_compaction_id": <string|null>,
        "state": {
            "type": "checkpoint",
            "durable": <object>,
            "active": [<side>, ...],
            "sides": {
                <non-main-side>: [<message>, ...],
            },
        } | {
            "type": "patch",
            "durable": <JSONPatch>,
            "active": [<side>, ...] | null,
            "sides": {
                <non-main-side>: <JSONPatch>,
            },
        },
        "main": [<message>..., <optional-postfix-message-patch>],
    }

- Compaction envelope:

    {
        "version": 4,
        "type": "compaction",
        "id": <string>,
        "durable": <object>,
        "sides": <Sides>,
    }

- Side snapshot:

    {
        "active": [<side>, ...],
        "messages": {
            <side>: [<message>, ...],
        },
    }

- Reasoning checkpoints replace durable state, active membership, and every non-main
  side. Reasoning patches apply deltas to those fields. Main always uses the
  common append-only `main` lane and is never checkpointed by reasoning.
- `previous_compaction_id` is null before any compaction and otherwise equals
  the latest replayed compaction ID for every checkpoint and patch.

- The JSON bytes are compressed with zstd, then encrypted with
  PyNaCl `nacl.secret.Aead`, which uses XChaCha20-Poly1305-IETF.
- Parameters:
  - key: the 32-byte purpose-derived key
  - AAD: `b"plap:" + purpose`
  - nonce: a random 24-byte nonce generated by `Aead.encrypt()`
- PyNaCl returns the combined blob as:

    nonce[24] || ciphertext[len(compressed)] || tag[16]

- The stored string is unpadded base64url of that combined blob.
- There is no textual prefix for reasoning/compaction strings; only the
  call-id layer adds one.

Sealed call ids
- Text form:

    "call_" + base64url_unpadded(aes_siv_output)

- Before encryption, the plaintext byte layout is:

    header[1]
    || side_code_be_u16[2]
    || encoded_upstream_tool_call_id[bytes]

- `header` bit layout:
  - bits 7..4: format version (`2`)
  - bits 3..2: reserved and must be zero
  - bits 1..0: upstream id codec

- Upstream id codecs:
  - `00 = utf8`
  - `01 = ascii7`
  - `10 = base64url6`
  - `11` is reserved

- `side_code_be_u16` is the side code as an unsigned 16-bit big-endian integer.

 - Side codes come from `config.sides` in the loaded CUE config.
 - Only configured sides may be encoded or decoded.
 - Other `u16` values are unassigned.

- `encoded_upstream_tool_call_id` decodes to the required, non-empty UTF-8
  `upstream_tool_call_id`.
- Packed codecs store:

    packed_meta[1] || packed_bytes[...]

- `packed_meta` bit layout:
  - bits 7..3: reserved and must be zero
  - bits 2..0: unused bits in the final packed byte
- `ascii7` packs one 7-bit ASCII byte per symbol.
- `base64url6` packs one 6-bit symbol per base64url character using alphabet:
  `A-Z a-z 0-9 - _`.

Call-id encryption
- Call-id plaintext is encrypted with `cryptography` `AESSIV`.
- Parameters:
  - key: the 32-byte purpose-derived key
  - associated_data: `[b"plap:responses.ingest.call_id"]`
- No nonce is supplied, so this layer is deterministic AES-SIV.
- `AESSIV.encrypt()` returns:

    siv_tag[16] || ciphertext[len(plaintext)]

- The final external string is the `"call_"` prefix plus unpadded
  base64url of that byte sequence.
"""

